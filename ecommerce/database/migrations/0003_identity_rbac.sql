-- =============================================================================
-- 0003 identity, sessions and RBAC.
--
-- Three deliberately separate identity realms:
--   1. customer        — storefront shoppers (registered)
--   2. guest_session   — guest checkout identity, no customer row is faked
--   3. admin_user      — e-commerce back office, never the ERP identity
--
-- Customer cookies and admin cookies are different cookies, different tables
-- and different permission models. An ERP administrator cannot log in here and
-- a customer can never reach /api/v1/admin/*.
-- =============================================================================

CREATE TABLE "admin_user" (
  "admin_user_id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "email" varchar(255) UNIQUE NOT NULL CHECK ("email" = lower("email")),
  "password_hash" varchar(255) NOT NULL,
  "display_name" varchar(120) NOT NULL,
  "status" varchar(20) NOT NULL DEFAULT 'active'
    CHECK ("status" IN ('active', 'disabled')),
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  "last_login_at" timestamptz
);

CREATE TABLE "admin_role" (
  "role_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "role_name" varchar(40) UNIQUE NOT NULL,
  "description" varchar(255),
  "is_system" boolean NOT NULL DEFAULT false
);

CREATE TABLE "admin_permission" (
  "permission_code" varchar(60) PRIMARY KEY,
  "description" varchar(255) NOT NULL
);

CREATE TABLE "admin_role_permission" (
  "role_id" int NOT NULL REFERENCES "admin_role" ("role_id") ON DELETE CASCADE,
  "permission_code" varchar(60) NOT NULL REFERENCES "admin_permission" ("permission_code") ON DELETE CASCADE,
  PRIMARY KEY ("role_id", "permission_code")
);

CREATE TABLE "admin_user_role" (
  "admin_user_id" uuid NOT NULL REFERENCES "admin_user" ("admin_user_id") ON DELETE CASCADE,
  "role_id" int NOT NULL REFERENCES "admin_role" ("role_id") ON DELETE CASCADE,
  PRIMARY KEY ("admin_user_id", "role_id")
);

CREATE TABLE "admin_session" (
  "session_id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "admin_user_id" uuid NOT NULL REFERENCES "admin_user" ("admin_user_id") ON DELETE CASCADE,
  "token_hash" char(64) UNIQUE NOT NULL,
  "csrf_token" varchar(64) NOT NULL,
  "expires_at" timestamptz NOT NULL,
  "revoked_at" timestamptz,
  "ip" inet,
  "user_agent" varchar(500),
  "created_at" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_admin_session_user ON "admin_session" ("admin_user_id", "expires_at");

CREATE TABLE "customer_session" (
  "session_id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "customer_id" int NOT NULL REFERENCES "customer" ("customer_id") ON DELETE CASCADE,
  "token_hash" char(64) UNIQUE NOT NULL,
  "csrf_token" varchar(64) NOT NULL,
  "expires_at" timestamptz NOT NULL,
  "revoked_at" timestamptz,
  "ip" inet,
  "user_agent" varchar(500),
  "created_at" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_customer_session_customer ON "customer_session" ("customer_id", "expires_at");

CREATE TABLE "guest_session" (
  "guest_session_id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "token_hash" char(64) UNIQUE NOT NULL,
  "csrf_token" varchar(64) NOT NULL,
  "email" varchar(255),
  "expires_at" timestamptz NOT NULL,
  "revoked_at" timestamptz,
  "ip" inet,
  "user_agent" varchar(500),
  "created_at" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE "customer_password_reset" (
  "token_hash" char(64) PRIMARY KEY,
  "customer_id" int NOT NULL REFERENCES "customer" ("customer_id") ON DELETE CASCADE,
  "expires_at" timestamptz NOT NULL,
  "used_at" timestamptz,
  "created_at" timestamptz NOT NULL DEFAULT now()
);

-- Security-relevant events for either identity realm.
CREATE TABLE "security_event" (
  "security_event_id" bigserial PRIMARY KEY,
  "subject_type" varchar(20) NOT NULL CHECK ("subject_type" IN ('customer', 'guest', 'admin')),
  "subject_id" varchar(64),
  "action" varchar(80) NOT NULL,
  "ip" inet,
  "metadata" jsonb NOT NULL DEFAULT '{}'::jsonb,
  "created_at" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_security_event_action ON "security_event" ("action", "created_at" DESC);

-- Digest-keyed buckets so raw emails/IPs are not stored as rate-limit keys.
CREATE TABLE "rate_limit_bucket" (
  "bucket_key" char(64) PRIMARY KEY,
  "window_start" timestamptz NOT NULL DEFAULT now(),
  "hits" int NOT NULL DEFAULT 1
);

-- Updated-at maintenance (single definition reused by later migrations).
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_customer_updated BEFORE UPDATE ON "customer"
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_admin_user_updated BEFORE UPDATE ON "admin_user"
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
