-- =============================================================================
-- 0002 approved catalogue extensions.
--   * brands and spec-sheet attributes (distinct from variant options)
--   * merchandising fields required by a public storefront
--   * all supplied `timestamp` columns normalised to `timestamptz` (stored UTC)
-- =============================================================================

-- Timestamps become timezone-aware (UTC) everywhere in the supplied ERD.
ALTER TABLE "customer" ALTER COLUMN "created_at" TYPE timestamptz USING "created_at" AT TIME ZONE 'UTC';
ALTER TABLE "product" ALTER COLUMN "created_at" TYPE timestamptz USING "created_at" AT TIME ZONE 'UTC';
ALTER TABLE "customer_order" ALTER COLUMN "created_at" TYPE timestamptz USING "created_at" AT TIME ZONE 'UTC';
ALTER TABLE "customer_order" ALTER COLUMN "updated_at" TYPE timestamptz USING "updated_at" AT TIME ZONE 'UTC';
ALTER TABLE "customer_order" ALTER COLUMN "order_date" TYPE timestamptz USING "order_date" AT TIME ZONE 'UTC';
ALTER TABLE "payment" ALTER COLUMN "created_at" TYPE timestamptz USING "created_at" AT TIME ZONE 'UTC';
ALTER TABLE "review" ALTER COLUMN "created_at" TYPE timestamptz USING "created_at" AT TIME ZONE 'UTC';
ALTER TABLE "promotion" ALTER COLUMN "start_date" TYPE timestamptz USING "start_date" AT TIME ZONE 'UTC';
ALTER TABLE "promotion" ALTER COLUMN "end_date" TYPE timestamptz USING "end_date" AT TIME ZONE 'UTC';

CREATE TABLE "brand" (
  "brand_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "brand_name" varchar(120) UNIQUE NOT NULL,
  "slug" varchar(140) UNIQUE NOT NULL,
  "logo_url" varchar(500),
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

-- Product attributes describe a product (material, weight, care). Variant
-- options (product_option/product_option_value) *generate* variants. They are
-- deliberately different concepts and must not be conflated.
CREATE TABLE "product_attribute" (
  "attribute_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "attribute_key" varchar(60) UNIQUE NOT NULL,
  "attribute_label" varchar(120) NOT NULL,
  "data_type" varchar(20) NOT NULL DEFAULT 'text'
    CHECK ("data_type" IN ('text', 'number', 'boolean')),
  "unit" varchar(20),
  "is_filterable" boolean NOT NULL DEFAULT false,
  "sort_order" int NOT NULL DEFAULT 1
);

CREATE TABLE "product_attribute_assignment" (
  "product_id" int NOT NULL,
  "attribute_id" int NOT NULL,
  "value_text" varchar(255) NOT NULL,
  PRIMARY KEY ("product_id", "attribute_id")
);

CREATE TABLE "product_attribute_option" (
  "attribute_id" int NOT NULL,
  "value_text" varchar(120) NOT NULL,
  "sort_order" int NOT NULL DEFAULT 1,
  PRIMARY KEY ("attribute_id", "value_text")
);

-- ---------------------------------------------------------------------------
-- Catalogue merchandising columns
-- ---------------------------------------------------------------------------
ALTER TABLE "product"
  ADD COLUMN "brand_id" int,
  ADD COLUMN "slug" varchar(180),
  ADD COLUMN "summary" varchar(400),
  ADD COLUMN "status" varchar(20) NOT NULL DEFAULT 'draft'
    CHECK ("status" IN ('draft', 'active', 'archived')),
  ADD COLUMN "is_featured" boolean NOT NULL DEFAULT false,
  ADD COLUMN "seo_title" varchar(200),
  ADD COLUMN "seo_description" varchar(400),
  ADD COLUMN "tax_class" varchar(40) NOT NULL DEFAULT 'standard',
  ADD COLUMN "updated_at" timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN "erp_updated_at" timestamptz,
  ADD COLUMN "sync_state" varchar(20) NOT NULL DEFAULT 'pending'
    CHECK ("sync_state" IN ('pending', 'synced', 'local_only', 'error'));

ALTER TABLE "product" ADD FOREIGN KEY ("brand_id") REFERENCES "brand" ("brand_id");
CREATE UNIQUE INDEX uq_product_slug ON "product" ("slug") WHERE "slug" IS NOT NULL;
CREATE INDEX idx_product_status ON "product" ("status", "is_featured");

ALTER TABLE "category"
  ADD COLUMN "slug" varchar(140),
  ADD COLUMN "description" text,
  ADD COLUMN "image_url" varchar(500),
  ADD COLUMN "is_active" boolean NOT NULL DEFAULT true,
  ADD COLUMN "sort_order" int NOT NULL DEFAULT 1,
  ADD COLUMN "updated_at" timestamptz NOT NULL DEFAULT now();
CREATE UNIQUE INDEX uq_category_slug ON "category" ("slug") WHERE "slug" IS NOT NULL;

ALTER TABLE "product_variant"
  ADD COLUMN "barcode" varchar(64),
  ADD COLUMN "compare_at_price" decimal(10,2),
  ADD COLUMN "weight_grams" int,
  ADD COLUMN "is_default" boolean NOT NULL DEFAULT false,
  ADD COLUMN "is_active" boolean NOT NULL DEFAULT true,
  ADD COLUMN "updated_at" timestamptz NOT NULL DEFAULT now();
ALTER TABLE "product_variant"
  ADD CONSTRAINT ck_variant_price CHECK ("price" >= 0),
  ADD CONSTRAINT ck_variant_stock CHECK ("qty_in_stock" >= 0),
  ADD CONSTRAINT ck_variant_weight CHECK ("weight_grams" IS NULL OR "weight_grams" >= 0),
  ADD CONSTRAINT ck_variant_compare_price CHECK ("compare_at_price" IS NULL OR "compare_at_price" >= "price");
CREATE UNIQUE INDEX uq_variant_barcode ON "product_variant" ("barcode") WHERE "barcode" IS NOT NULL;
CREATE UNIQUE INDEX uq_variant_default ON "product_variant" ("product_id") WHERE "is_default" = true;
CREATE INDEX idx_variant_product ON "product_variant" ("product_id");
CREATE INDEX idx_variant_stock ON "product_variant" ("qty_in_stock");

ALTER TABLE "product_option"
  ADD COLUMN "sort_order" int NOT NULL DEFAULT 1,
  ADD COLUMN "display_name" varchar(80);
ALTER TABLE "product_option_value"
  ADD COLUMN "sort_order" int NOT NULL DEFAULT 1,
  ADD COLUMN "hex_value" char(7);
ALTER TABLE "product_image"
  ADD COLUMN "alt_text" varchar(255),
  ADD COLUMN "is_primary" boolean NOT NULL DEFAULT false,
  ADD COLUMN "width" int,
  ADD COLUMN "height" int;
CREATE UNIQUE INDEX uq_product_primary_image ON "product_image" ("product_id") WHERE "is_primary" = true;
CREATE INDEX idx_product_image_product ON "product_image" ("product_id", "sort_order");

ALTER TABLE "shipping_method"
  ADD COLUMN "code" varchar(40),
  ADD COLUMN "is_active" boolean NOT NULL DEFAULT true,
  ADD COLUMN "min_days" int,
  ADD COLUMN "max_days" int;
CREATE UNIQUE INDEX uq_shipping_method_code ON "shipping_method" ("code") WHERE "code" IS NOT NULL;
ALTER TABLE "shipping_method" ADD CONSTRAINT ck_shipping_price CHECK ("price" >= 0);

-- ---------------------------------------------------------------------------
-- Customer account extensions
-- ---------------------------------------------------------------------------
ALTER TABLE "customer"
  ADD COLUMN "status" varchar(20) NOT NULL DEFAULT 'active'
    CHECK ("status" IN ('active', 'disabled')),
  ADD COLUMN "email_verified_at" timestamptz,
  ADD COLUMN "marketing_opt_in" boolean NOT NULL DEFAULT false,
  ADD COLUMN "last_login_at" timestamptz,
  ADD COLUMN "updated_at" timestamptz NOT NULL DEFAULT now();
COMMENT ON COLUMN "customer"."status" IS 'Disabled customers cannot authenticate or check out';
ALTER TABLE "customer" ADD CONSTRAINT ck_customer_email_lower CHECK ("email" = lower("email"));

CREATE TABLE "customer_address_link" (
  "customer_id" int NOT NULL,
  "address_id" int NOT NULL,
  "label" varchar(40),
  PRIMARY KEY ("customer_id", "address_id")
);

-- Promotions: unique names, sane windows, explicit scope, and a redemption log.
ALTER TABLE "promotion"
  ADD COLUMN "code" varchar(40),
  ADD COLUMN "is_active" boolean NOT NULL DEFAULT true,
  ADD COLUMN "min_order_total" decimal(10,2),
  ADD COLUMN "max_redemptions" int,
  ADD COLUMN "redemption_count" int NOT NULL DEFAULT 0;
ALTER TABLE "promotion"
  ADD CONSTRAINT ck_promotion_type CHECK ("discount_type" IN ('percentage', 'fixed')),
  ADD CONSTRAINT ck_promotion_window CHECK ("end_date" > "start_date"),
  ADD CONSTRAINT ck_promotion_value CHECK ("discount_value" >= 0),
  ADD CONSTRAINT ck_promotion_redemptions CHECK ("redemption_count" >= 0);
CREATE UNIQUE INDEX uq_promotion_code ON "promotion" ("code") WHERE "code" IS NOT NULL;
ALTER TABLE "promotion_product" ADD FOREIGN KEY ("promotion_id") REFERENCES "promotion" ("promotion_id") ON DELETE CASCADE;

CREATE TABLE "promotion_redemption" (
  "redemption_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "promotion_id" int NOT NULL REFERENCES "promotion" ("promotion_id"),
  "order_id" int NOT NULL,
  "customer_id" int,
  "amount" decimal(10,2) NOT NULL CHECK ("amount" >= 0),
  "created_at" timestamptz NOT NULL DEFAULT now(),
  UNIQUE ("promotion_id", "order_id")
);
